"""Make the notebook's kernel start reliably on Windows.

    conda activate spatiotemporal
    python tools/install_kernel.py

Two independent fixes, because a front end can start a kernel in two different ways.

**Why either is needed.** NumPy delay-loads its BLAS library (``libblas.dll``, in the
environment's ``Library\\bin``). Windows resolves a delay-loaded DLL through PATH, and
launching ``<env>\\python.exe`` without activating the environment leaves ``Library\\bin``
off PATH. The load then fails as a structured exception, 0xc06d007f, inside NumPy's
``blas_fpe_check`` at import. That aborts the process instead of raising, so a front end
reports only "the kernel died" with no traceback. Measured here:
``python.exe -c "import numpy"`` exits -1066598273.

1. ``install_kernelspec`` writes a per-user kernelspec that activates the environment
   before starting the kernel. In VS Code this appears under *Jupyter Kernel* as
   "Python (spatiotemporal)".
2. ``install_path_fix`` writes a ``.pth`` into the environment that prepends
   ``Library\\bin`` to PATH at interpreter startup, before any import. This covers front
   ends that bypass the kernelspec and launch the interpreter themselves, which is what VS
   Code does when the kernel is chosen under *Python Environments* (shown there as
   "spatiotemporal (Python 3.11.17)").

``os.add_dll_directory`` does not work for this: it affects ``LoadLibraryEx`` searches,
while delay-loading uses PATH. Setting ``os.environ["PATH"]`` does work, and is what the
``.pth`` does.

The kernelspec lives outside the environment and survives rebuilding its packages. The
``.pth`` lives inside it and does not, so re-run this script after recreating the
environment.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

KERNEL_NAME = "spatiotemporal"
DISPLAY_NAME = "Python (spatiotemporal)"


def kernel_directory() -> Path:
    """Return the per-user kernelspec directory for this kernel."""
    if os.name == "nt":
        base = Path(os.environ["APPDATA"]) / "jupyter"
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Jupyter"
    else:
        base = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "jupyter"
    return base / "kernels" / KERNEL_NAME


def conda_root(prefix: Path) -> Path:
    """Return the conda installation that owns ``prefix``.

    A named environment lives at ``<root>/envs/<name>``. ``sys.base_prefix`` is no help
    here: unlike a venv, a conda environment reports the same value as ``sys.prefix``.
    """
    if prefix.parent.name == "envs":
        return prefix.parent.parent
    return prefix


def write_windows_launcher(prefix: Path, target: Path) -> Path:
    """Write a batch file that activates ``prefix`` and launches the kernel.

    The activation goes in a batch file rather than straight into ``argv`` because the
    kernelspec's argv is handed to CreateProcess, which re-quotes each element: quotes
    around a path then arrive at cmd.exe escaped as \\" and it reports
    'is not recognized as an internal or external command'. Inside a batch file the
    quoting is plain, so paths containing spaces work.
    """
    activate = conda_root(prefix) / "Scripts" / "activate.bat"
    if not activate.is_file():
        raise FileNotFoundError(f"no activate.bat at {activate}; is {prefix} a conda environment?")
    launcher = target / "launch_kernel.bat"
    # %~1 strips any quotes the caller added, and the path is re-quoted here.
    script = (
        "@echo off\r\n"
        "rem Generated by tools/install_kernel.py. Activating puts the environment's\r\n"
        "rem Library\\bin on PATH; without it NumPy's DLLs fail to load and the kernel\r\n"
        "rem aborts with no traceback.\r\n"
        f'call "{activate}" "{prefix}"\r\n'
        'python -m ipykernel_launcher -f "%~1"\r\n'
    )
    with open(launcher, "w", encoding="ascii", newline="") as handle:
        handle.write(script)
    return launcher


def build_argv(prefix: Path, target: Path) -> list[str]:
    """Return an argv that activates ``prefix`` and then launches the kernel."""
    if os.name == "nt":
        return [str(write_windows_launcher(prefix, target)), "{connection_file}"]
    return [
        "conda",
        "run",
        "--no-capture-output",
        "-p",
        str(prefix),
        "python",
        "-m",
        "ipykernel_launcher",
        "-f",
        "{connection_file}",
    ]


PTH_NAME = "zz_conda_library_bin_on_path.pth"

# A .pth line is executed at interpreter startup when it starts with "import". The
# os.environ.__setitem__ call is written as an expression inside a conditional expression
# on purpose: `os.environ["PATH"] = x if cond else None` would clear PATH when cond is
# false. Everything must stay on one line, because .pth files are read line by line.
PTH_LINE = (
    'import os, sys; _lib = os.path.join(sys.prefix, "Library", "bin"); '
    '_path = os.environ.get("PATH", ""); '
    'os.environ.__setitem__("PATH", _lib + os.pathsep + _path) '
    'if (os.name == "nt" and os.path.isdir(_lib) '
    'and _lib.lower() not in _path.lower()) else None'
)


def site_packages(prefix: Path) -> Path:
    """Return the environment's site-packages directory."""
    if os.name == "nt":
        return prefix / "Lib" / "site-packages"
    version = f"python{sys.version_info.major}.{sys.version_info.minor}"
    return prefix / "lib" / version / "site-packages"


def install_path_fix(prefix: Path, remove: bool = False) -> Path | None:
    """Write (or delete) the .pth that puts the environment's Library\\bin on PATH."""
    target = site_packages(prefix) / PTH_NAME
    if remove:
        if target.exists():
            target.unlink()
            return target
        return None
    if os.name != "nt":
        return None
    # newline="" so the single line is not rewritten with CRLF.
    with open(target, "w", encoding="ascii", newline="") as handle:
        handle.write(PTH_LINE + "\n")
    return target


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--remove", action="store_true", help="uninstall the kernelspec")
    arguments = parser.parse_args()

    target = kernel_directory()
    prefix = Path(sys.prefix)
    if arguments.remove:
        if target.exists():
            shutil.rmtree(target)
            print(f"removed {target}")
        else:
            print(f"nothing to remove at {target}")
        removed = install_path_fix(prefix, remove=True)
        print(f"removed {removed}" if removed else "no PATH fix to remove")
        return

    if prefix == conda_root(prefix):
        raise SystemExit(
            f"{prefix} looks like the base conda installation. Run this from inside the "
            f"environment: conda activate spatiotemporal"
        )
    target.mkdir(parents=True, exist_ok=True)
    spec = {
        "argv": build_argv(prefix, target),
        "display_name": DISPLAY_NAME,
        "language": "python",
        "metadata": {"debugger": True},
    }
    # newline="" so Windows does not turn the JSON's line endings into CRLF.
    with open(target / "kernel.json", "w", encoding="utf-8", newline="") as handle:
        json.dump(spec, handle, indent=1)
        handle.write("\n")
    print(f"installed kernel {KERNEL_NAME!r} ({DISPLAY_NAME}) at {target}")
    print(f"  environment: {prefix}")
    pth = install_path_fix(prefix)
    if pth is not None:
        print(f"installed PATH fix at {pth}")
        print("  this also covers front ends that launch the interpreter directly")
    print("  in VS Code, pick this kernel with 'Select Kernel' at the top right of the notebook")


if __name__ == "__main__":
    main()
